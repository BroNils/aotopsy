func TestWriteFridaScriptRejectsDestructiveAliases(t *testing.T) {
	dir := t.TempDir()
	lib := filepath.Join(dir, "libapp.so")
	const original = "source-binary"
	if err := os.WriteFile(lib, []byte(original), 0o600); err != nil {
		t.Fatal(err)
	}
	hooks := []FridaHook{{VA: 0x1000, Name: "F"}}
	if err := WriteFridaScript(lib, dir, lib, true, hooks, nil, FridaOptions{}); err == nil {
		t.Fatal("Frida script output was allowed to overwrite source binary")
	}
	if b, err := os.ReadFile(lib); err != nil || string(b) != original {
		t.Fatalf("source binary changed after rejected alias: %q, %v", b, err)
	}

	combined := filepath.Join(dir, "combined.dart")
	if err := os.WriteFile(combined, []byte("previous decompile"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := WriteFridaScript(combined, dir, lib, true, hooks, nil, FridaOptions{}); err == nil {
		t.Fatal("Frida script output was allowed to overwrite combined.dart")
	}
	if b, err := os.ReadFile(combined); err != nil || string(b) != "previous decompile" {
		t.Fatalf("combined.dart changed after rejected alias: %q, %v", b, err)
	}
}
