func TestGenerateFridaScriptFromMeta(t *testing.T) {
	meta := FridaMetadata{
		SchemaVersion:      MetadataSchemaVersion,
		SourceSHA256:       testSourceSHA256,
		SourceSize:         1234,
		ModuleName:         "libapp.so",
		DartVersion:        "3.9.2",
		Architecture:       "arm64",
		CompressedPointers: true,
		PointerSize:        4,
		THRReg:             "x26",
		PPReg:              "x27",
		DTReg:              "x21",
		HeapBaseMode:       "heap_bits",
		HeapBaseReg:        "x28",
		HeaderBitOffset:    12,
		HeaderBitWidth:     20,
		Functions: []FridaFunction{
			{Name: "User.login", VA: "0x1000", Size: 64},
		},
		CallProbes: []FridaCallProbe{
			{VA: "0x1020", FromFunc: "User.login", TargetKind: "register", Reg: "x0"},
		},
		THRFields: map[int]string{0x70: "later", 0x48: "earlier"},
	}
	meta = finalizeTestMetadata(t, meta)

	script, err := GenerateFridaScript(meta)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(script, "Auto-generated by aotopsy frida-export") {
		t.Errorf("script missing header")
	}
	if !strings.Contains(script, "User.login") {
		t.Errorf("script missing function name")
	}
	if !strings.Contains(script, "0x1020") {
		t.Errorf("script missing BLR PC")
	}
	if !strings.Contains(script, runtimeEventPrefix) {
		t.Errorf("script missing machine-readable runtime event contract")
	}
	if !strings.Contains(script, "Process.attachThreadObserver") || !strings.Contains(script, "Process.getCurrentThreadId()") {
		t.Errorf("script still lacks supported Frida thread-name tracking")
	}
	if strings.Contains(script, "Thread.currentName") {
		t.Errorf("script uses removed/unsupported Thread.currentName API")
	}
	if strings.Index(script, `0x48: "earlier"`) > strings.Index(script, `0x70: "later"`) {
		t.Errorf("THR field emission is not deterministic/sorted")
	}
	if script2, err := GenerateFridaScript(meta); err != nil || script2 != script {
		t.Errorf("same metadata generated different Frida JavaScript")
	}
	if strings.Contains(script, "via: s.via") {
		t.Fatal("generated runtime dispatch event contains field rejected by importer schema")
	}
	for _, want := range []string{
		"new Checksum('sha256')",
		"Process.arch !== META.arch",
		"cursor.readByteArray(take)",
		"measuredRegionSHA256 !== region.sha256.toLowerCase()",
		"event.generation_id = META.generationID",
		"function_va: h.addr",
	} {
		if !strings.Contains(script, want) {
			t.Errorf("script missing runtime trust-boundary check %q", want)
		}
	}
	if strings.Contains(script, "MAX_HOOKS") || strings.Contains(script, "MAX_PROBES") {
		t.Fatal("runtime script still applies an unbound hook/probe cap")
	}
	if strings.Contains(script, "source_sha256: META.sourceSHA256") {
		t.Fatal("runtime event still self-asserts the static source hash instead of measured identity")
	}
}

func TestNewCallProbeStructuredTargets(t *testing.T) {
	reg, ok := NewCallProbe("0x100", "F", "X16", "")
	if !ok || reg.TargetKind != "register" || reg.Reg != "x16" {
		t.Fatalf("register probe = %+v,%v", reg, ok)
	}
	mem, ok := NewCallProbe("0x200", "F", "[RAX+RCX*8+0xd700]", "dispatch_table")
	if !ok || mem.TargetKind != "x86_mem" || mem.BaseReg != "rax" || mem.IndexReg != "rcx" || mem.Scale != 8 || mem.Disp != 0xd700 {
		t.Fatalf("x86 memory probe = %+v,%v", mem, ok)
	}
	if _, ok := NewCallProbe("0x300", "F", "[not parseable", ""); ok {
		t.Fatal("malformed memory target produced a runtime probe")
	}
	neg, ok := NewCallProbe("0x301", "F", "[RAX+RCX*8-0x20]", "")
	if !ok || neg.Disp != -0x20 {
		t.Fatalf("negative displacement probe = %+v,%v", neg, ok)
	}
	for _, target := range []string{"[RAX+0x7fffffff]", "[RAX-0x80000000]"} {
		if _, ok := NewCallProbe("0x302", "F", target, ""); !ok {
			t.Fatalf("valid signed disp32 target %q was rejected", target)
		}
	}
	for _, target := range []string{"[RAX+0x80000000]", "[RAX-0x80000001]"} {
		if _, ok := NewCallProbe("0x303", "F", target, ""); ok {
			t.Fatalf("impossible x86 displacement target %q produced a runtime probe", target)
		}
	}
}

