// The runtime-entry names these tables carry are no longer synthesised at
// init() time from a hand-written base offset. extract_thr derives them from
// the SDK's own anchors -- the first entry of each block, which
// runtime_offsets_extracted.h exports by name -- and writes them into the
// table literals, so what ships is what the header says rather than what a
// base offset predicts.
//
// The old mergeRuntimeEntries reported a conflict whenever its prediction
// disagreed with a name the table already had, and that signal was worth
// having: it is what showed the bases had drifted a slot. It is redundant
// now. `extract_thr -check` compares every committed table against the SDK
// field by field, and -check-runtime-entries additionally requires every
// entry in RUNTIME_ENTRY_LIST and LEAF_RUNTIME_ENTRY_LIST to be named in
// the table -- across all 46 version/arch pairs, not the 31 the header
// happens to export.

