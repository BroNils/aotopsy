#!/usr/bin/env bash
# Regenerate BENCHMARK.md from the ground-truth symtab differential.
# Requires the local ground-truth twins (real builds with .symtab, not
# redistributable). Reproduce with: make bench
set -euo pipefail
OUT="${1:-BENCHMARK.md}"
ROWS="$(mktemp)"
trap 'rm -f "$ROWS"' EXIT

echo "Running symtab differential (this needs the local ground-truth twins)..." >&2
go test ./internal/analysis/ -run TestSymtabDifferential -count=1 -timeout 60m -v 2>&1 \
  | grep -oE "BENCHROW	.*" | sed 's/^BENCHROW	//' > "$ROWS" || true

n="$(wc -l < "$ROWS" | tr -d ' ')"
if [ "$n" -eq 0 ]; then
  echo "No ground-truth samples with .symtab found; nothing to score." >&2
  exit 1
fi

commit="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
gen_date="$(date -u +%Y-%m-%d)"
# Weighted overall agreement across all compared symbols.
read -r tot_cmp tot_agr <<<"$(awk -F'	' '{c+=$3; a+=$4} END{print c, a}' "$ROWS")"
overall="$(awk -v a="$tot_agr" -v c="$tot_cmp" 'BEGIN{printf "%.1f", (c>0)?100*a/c:0}')"
worst="$(awk -F'	' 'NR==1||$2<m{m=$2} END{printf "%.1f", m}' "$ROWS")"

{
  echo "# Benchmark — Name-Recovery Accuracy vs Ground Truth"
  echo
  echo "AOTopsy's recovered function names, compared against each build's own ELF"
  echo "\`.symtab\` — the external ground truth. This is the accuracy claim other Flutter"
  echo "AOT tools do not publish. Generated by \`make bench\` (commit \`$commit\`, $gen_date)."
  echo
  echo "**Overall: ${overall}% agreement across ${tot_cmp} compared symbols.**"
  echo "Worst per-build band: ${worst}%. Gate floor (\`TestSymtabDifferential\`): 81%."
  echo
  echo "| Dart build | Arch | Agreement | Compared | Agree |"
  echo "|------------|------|-----------|----------|-------|"
  # sort by version (natural), then name
  sort -V "$ROWS" | while IFS=$'\t' read -r name rate compared agree; do
    arch="arm64"; case "$name" in *x64*) arch="x64";; esac
    ver="$(printf '%s' "$name" | sed -E 's/^dart-//; s/-gt//; s/-(arm64|x64)\.so$//')"
    printf '| %s | %s | %s%% | %s | %s |\n' "$ver" "$arch" "$rate" "$compared" "$agree"
  done
  echo
  echo "## Method"
  echo
  echo "- **Ground truth:** unstripped Dart builds carry a \`.symtab\`; stripped"
  echo "  production builds skip (nothing to compare). Names are matched by virtual"
  echo "  address via \`CompareNamesToSymbols\`."
  echo "- **Honest denominator:** \`stub_\`/\`sub_\`/\`SharedStub\` markers are \"we don't"
  echo "  know\" outputs, not name claims; they are excluded so the score neither"
  echo "  rewards guessing nor punishes honesty (§2)."
  echo "- **Reproduce:** \`make bench\` (requires the local ground-truth twins, which are"
  echo "  real builds we cannot redistribute)."
  echo "- **Not measured here:** decompiler syntax-validity (100%) and fabrication rate"
  echo "  (0%) are separate gates — see \`TestDecompileQualityCorpus\`."
} > "$OUT"

echo "Wrote $OUT ($n builds, overall ${overall}%)." >&2
